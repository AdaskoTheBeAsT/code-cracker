using CodeCracker.CSharp.Style;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.Diagnostics;
using System.Collections.Immutable;
using System.Threading;
using System.Threading.Tasks;
using Xunit;

namespace CodeCracker.Test.CSharp.Style
{
    public class AlwaysUseVarRobustnessTests : CodeFixVerifier<AlwaysUseVarAnalyzer, AlwaysUseVarCodeFixProvider>
    {
        [Fact]
        public async Task FixAllPreservesMixedFormsAcrossDocuments()
        {
            const string first = @"
using System.IO;
class C
{
    void M(int[] items, ref int input)
    {
        int local = 1;
        ref readonly int alias = ref input;
        using MemoryStream stream = new MemoryStream();
        bool parsed = int.TryParse(""1"", out int number);
        (int count, string name) = (1, ""name"");
        for (int index = 0; index < 1; index++) { }
        foreach (int item in items) { }
        int[] targetTyped = [1, 2];
    }
}";
            const string second = "class D { void M() { int first = 1, second = first + 1; } }";
            var expectedFirst = first.Replace("int local", "var local").Replace("readonly int alias", "readonly var alias")
                .Replace("MemoryStream stream", "var stream").Replace("bool parsed", "var parsed")
                .Replace("out int number", "out var number").Replace("(int count, string name)", "var (count, name)")
                .Replace("int index", "var index").Replace("int item", "var item");
            const string expectedSecond = "class D { void M() { var first = 1; var second = first + 1; } }";
            await VerifyCompilerValidCSharpFixAllAsync(new[] { first, second }, new[] { expectedFirst, expectedSecond },
                LanguageVersion.CSharp12, diagnosticCount: 9);
        }

        [Theory]
        [InlineData("// <auto-generated />\n")]
        [InlineData("[System.CodeDom.Compiler.GeneratedCode(\"test\", \"1\")]\n")]
        public async Task AllDeclarationFormsRespectGeneratedCode(string prefix)
        {
            var source = prefix + @"class C
{
    void M(int[] items)
    {
        int local = 1;
        _ = int.TryParse(""1"", out int number);
        (int first, int second) = (1, 2);
        for (int index = 0; index < 1; index++) { }
        foreach (int item in items) { }
    }
}";
            await VerifyCompilerValidCSharpNoDiagnosticAsync(source, LanguageVersion.CSharp12);
        }

        [Fact]
        public async Task AllDeclarationFormsRespectPragmaSuppression()
        {
            const string source = @"
#pragma warning disable CC0001, CC0105
class C
{
    void M(int[] items)
    {
        int local = 1;
        _ = int.TryParse(""1"", out int number);
        (int first, int second) = (1, 2);
        for (int index = 0; index < 1; index++) { }
        foreach (int item in items) { }
    }
}";
            await VerifyCompilerValidCSharpNoDiagnosticAsync(source, LanguageVersion.CSharp12);
        }

        [Fact]
        public async Task AnalysisCanBeCancelled()
        {
            var document = CreateCompilerValidCSharpDocument("class C { void M() { int value = 1; } }", LanguageVersion.CSharp12);
            var compilation = await document.Project.GetCompilationAsync(TestContext.Current.CancellationToken);
            using (var cancellation = new CancellationTokenSource())
            {
                cancellation.Cancel();
                await Assert.ThrowsAnyAsync<System.OperationCanceledException>(async () =>
                    await compilation.WithAnalyzers(ImmutableArray.Create<DiagnosticAnalyzer>(new AlwaysUseVarAnalyzer()))
                        .GetAnalyzerDiagnosticsAsync(cancellation.Token));
            }
        }

        [Theory]
        [InlineData(LanguageVersion.CSharp6)]
        [InlineData(LanguageVersion.CSharp7)]
        [InlineData(LanguageVersion.CSharp8)]
        [InlineData(LanguageVersion.CSharp9)]
        [InlineData(LanguageVersion.CSharp10)]
        [InlineData(LanguageVersion.CSharp11)]
        [InlineData(LanguageVersion.CSharp12)]
        [InlineData(LanguageVersion.CSharp13)]
        [InlineData(LanguageVersion.CSharp14)]
        public async Task OrdinaryLocalsKeepTheirLanguageVersionBehavior(LanguageVersion language)
        {
            const string source = "class C { void M() { int value = 1; } }";
            await VerifyCompilerValidCSharpFixAsync(source, source.Replace("int value", "var value"), language,
                diagnosticId: "CC0105", diagnosticText: "int");
        }

        [Fact]
        public async Task FixAllKeepsNullableDirectivesAndComments()
        {
            const string source = @"
#nullable enable
class C
{
    void M()
    {
        int /* count */ count = 1;
        string? /* name */ name = ""name"";
#nullable disable
        int later = 2;
    }
}";
            await VerifyCompilerValidCSharpFixAsync(source,
                source.Replace("int /* count */", "var /* count */").Replace("string? /* name */", "var /* name */")
                    .Replace("int later", "var later"),
                LanguageVersion.CSharp8, diagnosticCount: 3, fixAll: true);
        }

        [Fact]
        public async Task TypedOutDiscardIsConservativelyIgnored()
        {
            await VerifyCompilerValidCSharpNoDiagnosticAsync(
                "class C { void M() { _ = int.TryParse(\"1\", out int _); } }", LanguageVersion.CSharp7);
        }
    }
}
